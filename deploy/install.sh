#!/usr/bin/env bash
# piwebui — server-side installer.
#
#   tar -xzf piwebui-deploy-XXXX.tar.gz -C /tmp
#   sudo bash /tmp/piwebui-deploy/deploy/install.sh
#
# Flags:
#   --with-whisper   also install the faster-whisper sidecar (Python venv + model)
#   --no-whisper     skip it even if python3 is present (default: ask-free auto)
#   --port N         listen port for the relay (default 8787)
#
# Idempotent: existing .env files are NEVER overwritten, so re-running an upgrade
# keeps your tokens. Everything else is replaced.
set -euo pipefail

PREFIX="/opt/piwebui"
SERVICE_USER="piwebui"
PORT="8787"
WHISPER="auto"
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

while [ $# -gt 0 ]; do
	case "$1" in
		--with-whisper) WHISPER="yes"; shift ;;
		--no-whisper)   WHISPER="no";  shift ;;
		--port)         PORT="${2:-8787}"; shift 2 ;;
		--src)          SRC="${2:?--src needs a path}"; shift 2 ;;
		-h|--help)      sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
		*) echo "unknown flag: $1" >&2; exit 2 ;;
	esac
done

# ── pretty output ───────────────────────────────────────────────────────
if [ -t 1 ]; then
	C_HEAD=$'\033[36m'; C_OK=$'\033[32m'; C_ERR=$'\033[31m'; C_WARN=$'\033[33m'; C_OFF=$'\033[0m'
else
	C_HEAD=""; C_OK=""; C_ERR=""; C_WARN=""; C_OFF=""
fi
step() { printf '\n%s==> %s%s\n' "$C_HEAD" "$*" "$C_OFF"; }
ok()   { printf '%s  ok%s  %s\n' "$C_OK" "$C_OFF" "$*"; }
warn() { printf '%s  !!%s  %s\n' "$C_WARN" "$C_OFF" "$*"; }
die()  { printf '\n%s  xx%s  %s\n' "$C_ERR" "$C_OFF" "$*" >&2; exit 1; }

# ── preflight ───────────────────────────────────────────────────────────
[ "$(id -u)" -eq 0 ] || die "run as root: sudo bash $0"

step "preflight"
[ -f "$SRC/server/dist/index.js" ] || die "not a deploy bundle: $SRC/server/dist/index.js missing"
[ -f "$SRC/server/public/index.html" ] || die "frontend build missing: $SRC/server/public/index.html"

command -v node >/dev/null 2>&1 || die "node not found. Install Node 20+ first (nodesource or nvm)."
NODE_MAJOR="$(node -p 'process.versions.node.split(".")[0]')"
[ "$NODE_MAJOR" -ge 20 ] || die "node $(node -v) is too old; need >= 20"
ok "node $(node -v)"

command -v npm >/dev/null 2>&1 || die "npm not found alongside node"

if [ "$WHISPER" = "auto" ]; then
	if command -v python3 >/dev/null 2>&1; then WHISPER="yes"; else WHISPER="no"; fi
fi
if [ "$WHISPER" = "yes" ]; then
	command -v python3 >/dev/null 2>&1 || die "--with-whisper needs python3"
	PY_VER="$(python3 -c 'import sys;print("%d.%d"%sys.version_info[:2])')"
	ok "python $PY_VER"
	python3 -c 'import sys; sys.exit(0 if sys.version_info>=(3,9) else 1)' \
		|| die "python3 >= 3.9 required for faster-whisper"
fi

# ── user + dirs ─────────────────────────────────────────────────────────
step "system user"
if id "$SERVICE_USER" >/dev/null 2>&1; then
	ok "user $SERVICE_USER already exists"
else
	# --system: no aging, no password, lowest priority. nologin: cannot ssh in.
	useradd --system --shell /usr/sbin/nologin --home-dir "$PREFIX" --create-home "$SERVICE_USER"
	ok "created system user $SERVICE_USER"
fi

install -d -o "$SERVICE_USER" -g "$SERVICE_USER" -m 755 "$PREFIX/server"
install -d -o "$SERVICE_USER" -g "$SERVICE_USER" -m 755 "$PREFIX/whisper"

# ── server files ────────────────────────────────────────────────────────
step "installing relay server"
rm -rf "$PREFIX/server/dist" "$PREFIX/server/public"
cp -r "$SRC/server/dist" "$PREFIX/server/dist"
cp -r "$SRC/server/public" "$PREFIX/server/public"
cp "$SRC/server/package.json" "$PREFIX/server/package.json"
[ -f "$PREFIX/server/.env.example" ] || cp "$SRC/server/.env.example" "$PREFIX/server/.env.example"
ok "code copied to $PREFIX/server"

step "installing node dependencies"
( cd "$PREFIX/server" && npm install --omit=dev --no-audit --no-fund --loglevel=error )
ok "hono / @hono/node-server / ws installed"

# ── secrets ─────────────────────────────────────────────────────────────
step "configuration"
ENV_FILE="$PREFIX/server/.env"
if [ -f "$ENV_FILE" ]; then
	ok ".env exists, keeping your tokens"
	FRESH_ENV=0
else
	ACCESS_TOKEN="$(node -e 'process.stdout.write(require("crypto").randomBytes(32).toString("base64url"))')"
	AGENT_SECRET="$(node -e 'process.stdout.write(require("crypto").randomBytes(32).toString("hex"))')"
	SESSION_SECRET="$(node -e 'process.stdout.write(require("crypto").randomBytes(32).toString("hex"))')"

	cat > "$ENV_FILE" <<EOF
# generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)

HOST=127.0.0.1
PORT=$PORT

# Web login token
ACCESS_TOKEN=$ACCESS_TOKEN

# Shared with the local agent-host. MUST match its AGENT_SECRET.
AGENT_SECRET=$AGENT_SECRET

SESSION_SECRET=$SESSION_SECRET
SESSION_TTL_DAYS=30

# true once you serve over https (behind nginx + certbot)
SECURE_COOKIES=true

WHISPER_URL=http://127.0.0.1:8001
WHISPER_TOKEN=

MAX_UPLOAD_MB=25
PUBLIC_DIR=public
TRUST_PROXY=true
EOF
	chmod 600 "$ENV_FILE"
	FRESH_ENV=1
	ok "generated $ENV_FILE (mode 600)"
fi
chown "$SERVICE_USER:$SERVICE_USER" "$ENV_FILE"

# ── whisper ─────────────────────────────────────────────────────────────
if [ "$WHISPER" = "yes" ]; then
	step "installing faster-whisper sidecar"
	cp "$SRC/whisper/app.py" "$PREFIX/whisper/app.py"
	cp "$SRC/whisper/requirements.txt" "$PREFIX/whisper/requirements.txt"
	cp -n "$SRC/whisper/.env.example" "$PREFIX/whisper/.env.example"

	if [ ! -f "$PREFIX/whisper/.env" ]; then
		cat > "$PREFIX/whisper/.env" <<'EOF'
# generated by install.sh
WHISPER_MODEL=small
WHISPER_DEVICE=cpu
WHISPER_COMPUTE_TYPE=int8
WHISPER_LANGUAGE=

# HuggingFace mirror for mainland networks.
# HF_HUB_DISABLE_XET=1 is NOT optional: the mirror does not speak HF's Xet
# transfer protocol, so with the mirror alone you get
#   401 Unauthorized ... cas-server.xethub.hf.co
HF_ENDPOINT=https://hf-mirror.com
HF_HUB_DISABLE_XET=1
EOF
		chmod 600 "$PREFIX/whisper/.env"
		ok "generated whisper/.env (mirror + xet disabled)"
	else
		ok "whisper/.env exists, keeping it"
	fi

	if [ ! -x "$PREFIX/whisper/.venv/bin/uvicorn" ]; then
		python3 -m venv "$PREFIX/whisper/.venv"
		"$PREFIX/whisper/.venv/bin/pip" install --quiet --upgrade pip
		# av is pinned <16 in requirements.txt; installing takes a few minutes.
		"$PREFIX/whisper/.venv/bin/pip" install --quiet -r "$PREFIX/whisper/requirements.txt"
		ok "python venv ready"
	else
		ok "python venv already exists"
	fi
	chown -R "$SERVICE_USER:$SERVICE_USER" "$PREFIX/whisper"
else
	warn "skipping whisper — text/images only, voice button will report 502"
	[ -f "$PREFIX/whisper/.env" ] || echo "WHISPER_MODEL=small" > "$PREFIX/whisper/.env"
	chown -R "$SERVICE_USER:$SERVICE_USER" "$PREFIX/whisper"
fi

chown -R "$SERVICE_USER:$SERVICE_USER" "$PREFIX/server"

# ── systemd ─────────────────────────────────────────────────────────────
step "systemd units"
install -m 644 "$SRC/deploy/piwebui-server.service" /etc/systemd/system/
if [ "$WHISPER" = "yes" ]; then
	install -m 644 "$SRC/deploy/piwebui-whisper.service" /etc/systemd/system/
fi
systemctl daemon-reload
systemctl enable piwebui-server >/dev/null 2>&1 || true
if [ "$WHISPER" = "yes" ]; then
	systemctl enable piwebui-whisper >/dev/null 2>&1 || true
	systemctl restart piwebui-whisper
	ok "piwebui-whisper started (first run downloads ~460MB model, be patient)"
fi
systemctl restart piwebui-server
ok "piwebui-server started"

# ── health check ────────────────────────────────────────────────────────
step "health check"
LISTEN_OK=0
for _ in $(seq 1 30); do
	if curl -fsS -m 2 "http://127.0.0.1:$PORT/api/status" >/dev/null 2>&1; then
		LISTEN_OK=1
		break
	fi
	sleep 1
done
if [ "$LISTEN_OK" -eq 1 ]; then
	ok "relay answering on 127.0.0.1:$PORT"
else
	warn "no answer on 127.0.0.1:$PORT yet. Check: journalctl -u piwebui-server -n 50 --no-pager"
fi

if [ "$WHISPER" = "yes" ]; then
	W_OK=0
	for _ in $(seq 1 20); do
		if curl -fsS -m 2 "http://127.0.0.1:8001/health" >/dev/null 2>&1; then W_OK=1; break; fi
		sleep 2
	done
	if [ "$W_OK" -eq 1 ]; then ok "whisper answering on 127.0.0.1:8001"
	else warn "whisper still loading the model — that is normal on first boot"; fi
fi

# ── summary ─────────────────────────────────────────────────────────────
ACCESS_TOKEN_SHOWN="$(grep -E '^ACCESS_TOKEN=' "$ENV_FILE" | cut -d= -f2-)"
AGENT_SECRET_SHOWN="$(grep -E '^AGENT_SECRET=' "$ENV_FILE" | cut -d= -f2-)"

cat <<EOF

${C_OK}────────────────────────────────────────────────────────────${C_OFF}
  Server side is up. Next: nginx + TLS, then your local machine.

  1) nginx
       sudo cp $SRC/deploy/nginx.conf /etc/nginx/sites-available/piwebui
       sudo ln -sf /etc/nginx/sites-available/piwebui /etc/nginx/sites-enabled/
       #   edit server_name + the two cert paths inside first
       sudo nginx -t && sudo systemctl reload nginx
       sudo certbot --nginx -d your.domain

  2) Point your domain's A record at this box, then open
       https://your.domain
     and log in with this token:

       ${C_OK}${ACCESS_TOKEN_SHOWN}${C_OFF}

  3) On your own machine, create agent-host/.env:

       PIWEBUI_SERVER_URL=wss://your.domain/agent
       AGENT_SECRET=${AGENT_SECRET_SHOWN}
       PI_CWD=<absolute path to the project pi should work in>

     then start the bridge:
       Windows:  deploy\\start-agent.bat
       macOS/Linux: node agent-host/dist/agent-host.js

  Both tokens are also in ${ENV_FILE} (mode 600).
  Rotating ACCESS_TOKEN kicks every logged-in browser out; rotating
  AGENT_SECRET requires restarting the local bridge too.
${C_OK}────────────────────────────────────────────────────────────${C_OFF}

EOF

if [ "$FRESH_ENV" -eq 0 ]; then
	warn "This was an upgrade, not a first install — tokens above are your existing ones."
fi
